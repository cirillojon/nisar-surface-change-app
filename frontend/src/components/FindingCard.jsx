import { useEffect, useRef, useState } from "react";

import { absoluteApiUrl, fetchFinding } from "../services/api.js";

const dayFmt = new Intl.DateTimeFormat("en", { month: "short", day: "numeric", year: "numeric", timeZone: "UTC" });
const fmt = (iso) => (iso ? dayFmt.format(new Date(`${iso}T00:00:00Z`)) : "");
const period = (c) => (c.start === c.end ? fmt(c.start) : `${fmt(c.start)} – ${fmt(c.end)}`);
const round = (v) => (typeof v === "number" ? Math.round(v * 100) / 100 : v);

async function copy(text) {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    return false;
  }
}

/**
 * An evidence card: one moment of a curated story, as the app measured it,
 * to keep and share. The measured claim, the passes behind it, what the
 * record can and can't carry, labelled hypotheses, and every way to
 * reproduce it (link, CSV, REST, MCP, printable brief). Built by the API
 * (`/api/findings/<slug>`), so the card, the REST call and the MCP tool all
 * return the same thing. A story's "Save / share" opens it. With
 * `autoShow`, the card puts its place and pass on the map once loaded.
 */
export default function FindingCard({
  slug,
  moment = null,
  variant = "panel",
  saved = false,
  autoShow = false,
  onSave,
  onShowOnMap,
  onChangeMoment,
}) {
  const [finding, setFinding] = useState(null);
  const [error, setError] = useState(null);
  const [copied, setCopied] = useState(null);
  const showRef = useRef(onShowOnMap);
  showRef.current = onShowOnMap;

  useEffect(() => {
    let live = true;
    setFinding(null);
    setError(null);
    fetchFinding(slug, moment)
      .then((f) => {
        if (!live) return;
        setFinding(f);
        if (autoShow) showRef.current?.(f, { focusMap: false });
      })
      .catch((e) => live && setError(e?.message || "Couldn't build this finding."));
    return () => {
      live = false;
    };
  }, [slug, moment, autoShow]);

  if (error) return <p className="panel error" role="alert">{error}</p>;
  if (!finding) return <p className="panel muted" role="status">Building the finding…</p>;

  const { claim, confidence, evidence, links } = finding;
  const workspaceLink = `${window.location.origin}${links.workspace}`;
  const curl = `curl "${absoluteApiUrl(links.api)}"`;
  const mcp = JSON.stringify({ tool: links.mcp.tool, arguments: links.mcp.arguments }, null, 2);
  const briefHref = `/brief/${finding.story.slug}${finding.moment != null ? `?moment=${finding.moment}` : ""}`;
  const footprint = evidence.footprint;
  const showVisible = evidence.passes.some((p) => p.visible_value != null && p.visible_value !== p.value);
  const showMode = new Set(evidence.passes.map((p) => p.mode).filter(Boolean)).size > 1;
  const doCopy = async (what, text) => {
    const ok = await copy(text);
    setCopied(ok ? what : `${what}-failed`);
    window.setTimeout(() => setCopied(null), 1800);
  };
  const copyLabel = (what, label) =>
    copied === what ? "Copied ✓" : copied === `${what}-failed` ? "Copy blocked" : label;
  const ref = {
    slug: finding.story.slug,
    moment: finding.moment,
    title: finding.story.title,
    label: claim.measured ? `${claim.title} · ${claim.display}` : "Before & after",
  };
  const brief = variant === "brief";

  return (
    <article className={`finding-card finding-${variant}`} aria-label={`Finding: ${finding.story.title}`}>
      <header className="finding-head">
        <p className="finding-eyebrow small">
          Evidence card · generated by the app · {finding.site.name}
          {finding.site.product ? ` · NISAR ${finding.site.product}` : ""}
        </p>
        <h2>{finding.story.title}</h2>
        <p className="muted small">{finding.story.question}</p>
      </header>

      {finding.moments?.length > 1 && onChangeMoment && (
        <label className="finding-moment small">
          Moment{" "}
          <select value={finding.moment ?? ""} onChange={(e) => onChangeMoment(Number(e.target.value))}>
            {finding.moments.map((m) => (
              <option key={m.index} value={m.index}>{m.title} ({m.display})</option>
            ))}
          </select>
        </label>
      )}

      <section className="finding-claim" aria-label="What NISAR measured">
        <p className="finding-badge small">{claim.measured ? "Measured" : "Before & after, not measured"}</p>
        <p className={`finding-value${claim.measured ? "" : " finding-value-text"}`}>{claim.display}</p>
        <p className="finding-caption">{claim.caption}</p>
        <p className="muted small">
          {claim.measured ? `${claim.label} · ${claim.detail} · ` : ""}{period(claim)}
          {!claim.measured && finding.site.channels ? ` · ${finding.site.channels}` : ""}
        </p>
      </section>

      <section className="finding-section" aria-labelledby={`fc-conf-${slug}`}>
        <h3 id={`fc-conf-${slug}`}>What this rests on</h3>
        <p className="small">
          {confidence.passes} {confidence.passes === 1 ? "pass" : "passes"} in this period
          {confidence.longest_gap_days ? `, at most ${confidence.longest_gap_days} days apart` : ""}; the
          record holds {evidence.record_passes} over {confidence.record_days} days.
        </p>
        {confidence.notes.length > 0 && (
          <ul className="finding-notes small">{confidence.notes.map((n) => <li key={n}>{n}</li>)}</ul>
        )}
      </section>

      <section className="finding-section" aria-labelledby={`fc-ev-${slug}`}>
        <h3 id={`fc-ev-${slug}`}>Evidence</h3>
        <div className="finding-table-wrap">
          <table className="finding-table small">
            <thead>
              <tr>
                <th scope="col">Pass</th>
                {claim.measured && <th scope="col">{footprint ? `${claim.unit}, shared area` : claim.unit}</th>}
                {showVisible && <th scope="col">{claim.unit}, pixels it imaged</th>}
                {showMode && <th scope="col">Mode</th>}
                <th scope="col">Quality</th>
                <th scope="col">Box imaged</th>
              </tr>
            </thead>
            <tbody>
              {evidence.passes.map((p) => (
                <tr key={p.date}>
                  <td>{fmt(p.date)}</td>
                  {claim.measured && <td className="num">{round(p.value) ?? "–"}</td>}
                  {showVisible && <td className="num">{round(p.visible_value) ?? "–"}</td>}
                  {showMode && <td><code>{p.mode ?? "–"}</code></td>}
                  <td>{p.quality ?? "–"}</td>
                  <td className="num">{p.valid_pct != null ? `${Math.round(p.valid_pct)}%` : "–"}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
        {footprint && footprint.status === "ok" && footprint.pct_of_box < 99.95 && (
          <p className="small muted">
            Open water is compared over the {footprint.pct_of_box}% of the box that all {footprint.passes} passes imaged.
            {footprint.method === "image" && footprint.estimated?.length
              ? ` Values for passes that imaged more are estimated from the scene images, to within about ±${footprint.uncertainty_pp} points.`
              : ""}
          </p>
        )}
        {evidence.passes.some((p) => p.granule_id) && (
          <details className="small finding-granules">
            <summary>Granule IDs</summary>
            <ul>{evidence.passes.filter((p) => p.granule_id).map((p) => <li key={p.granule_id}><code>{p.granule_id}</code></li>)}</ul>
          </details>
        )}
        {evidence.sources?.length > 0 && (
          <p className="small">
            Reported by:{" "}
            {evidence.sources.map((s, i) => (
              <span key={s.url}>{i > 0 && " · "}<a href={s.url} target="_blank" rel="noreferrer">{s.label}</a></span>
            ))}
          </p>
        )}
      </section>

      {(finding.hypotheses.length > 0 || finding.compare_with?.length > 0) && (
        <section className="finding-section" aria-labelledby={`fc-hyp-${slug}`}>
          <h3 id={`fc-hyp-${slug}`}>Possible explanations</h3>
          {finding.hypotheses.length > 0 && (
            <>
              <p className="small muted">{finding.hypothesis_label}.</p>
              <ul className="finding-hyps">
                {finding.hypotheses.map((h) => (
                  <li key={h.id}>
                    <strong>{h.driver}.</strong> {h.mechanism}
                    <p className="small muted">{h.channel}</p>
                    <p className="small"><strong>Fits:</strong> {h.consistent_with}</p>
                    <p className="small"><strong>But:</strong> {h.alternative}</p>
                    <p className="small"><strong>Test:</strong> {h.test}</p>
                  </li>
                ))}
              </ul>
            </>
          )}
          {finding.compare_with?.length > 0 && (
            <p className="small muted">
              Compare with: {finding.compare_with.map((d) => `${d.label} (${d.summary})`).join("; ")}.{" "}
              {finding.comparison_note}
            </p>
          )}
        </section>
      )}

      <section className="finding-section" aria-labelledby={`fc-cant-${slug}`}>
        <h3 id={`fc-cant-${slug}`}>What this can&apos;t show</h3>
        <ul className="small">{finding.cant_see.map((c) => <li key={c}>{c}</li>)}</ul>
        {finding.next && <p className="small"><strong>With a longer record:</strong> {finding.next.application}</p>}
      </section>

      <section className="finding-section finding-cite" aria-labelledby={`fc-cite-${slug}`}>
        <h3 id={`fc-cite-${slug}`}>Cite</h3>
        <p className="small">{finding.citation}</p>
        <p className="small muted">{finding.caveat}</p>
      </section>

      {!brief && (
        <footer className="finding-actions" aria-label="Share and reproduce">
          <div className="finding-actions-row">
            {onShowOnMap && (
              <button type="button" className="btn btn-small btn-primary" onClick={() => onShowOnMap(finding)}>
                Show on map
              </button>
            )}
            {saved ? (
              <button type="button" className="btn btn-small btn-secondary" disabled>Saved in My findings</button>
            ) : (
              onSave && <button type="button" className="btn btn-small btn-secondary" onClick={() => onSave(ref, finding)}>Save to My findings…</button>
            )}
            <button type="button" className="btn btn-small btn-secondary" onClick={() => doCopy("link", workspaceLink)}>
              {copyLabel("link", "Copy link")}
            </button>
            <a className="btn btn-small btn-secondary" href={briefHref} target="_blank" rel="noreferrer">Printable brief</a>
            <button type="button" className="btn btn-small btn-secondary" onClick={() => doCopy("cite", finding.citation)}>
              {copyLabel("cite", "Copy citation")}
            </button>
          </div>
          <details className="finding-more small">
            <summary>Data &amp; code</summary>
            <div className="finding-actions-row">
              {links.csv && (
                <a className="btn btn-small btn-secondary" href={absoluteApiUrl(links.csv)} download>Download CSV</a>
              )}
              <button type="button" className="btn btn-small btn-secondary" onClick={() => doCopy("api", curl)}>
                {copyLabel("api", "Copy API call")}
              </button>
              <button type="button" className="btn btn-small btn-secondary" onClick={() => doCopy("mcp", mcp)}>
                {copyLabel("mcp", "Copy MCP call")}
              </button>
            </div>
          </details>
        </footer>
      )}
    </article>
  );
}
