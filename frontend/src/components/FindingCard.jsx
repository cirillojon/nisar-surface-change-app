import { useQuery } from "@tanstack/react-query";
import { useState } from "react";

import { absoluteApiUrl } from "../services/api.js";
import { findingQuery } from "../services/queries.js";

const dayFmt = new Intl.DateTimeFormat("en", { month: "short", day: "numeric", year: "numeric", timeZone: "UTC" });
const fmt = (iso) => (iso ? dayFmt.format(new Date(`${iso}T00:00:00Z`)) : "");
const period = (c) => (c.start === c.end ? fmt(c.start) : `${fmt(c.start)} – ${fmt(c.end)}`);
const round = (v) => (typeof v === "number" ? Math.round(v * 100) / 100 : v);
const plural = (n, one, many) => `${n} ${n === 1 ? one : many}`;

async function copy(text) {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    return false;
  }
}

/** What the card's Save hands on: where the finding is and what to call it. */
function findingRef(finding) {
  const { claim } = finding;
  return {
    slug: finding.story.slug,
    moment: finding.moment,
    title: finding.story.title,
    label: claim.measured ? `${claim.title} · ${claim.display}` : "Before & after",
  };
}

function FindingHead({ finding, onChangeMoment }) {
  const { site } = finding;
  return (
    <>
      <header className="finding-head">
        <p className="finding-eyebrow small">
          Evidence card · generated by the app · {site.name}
          {site.product ? ` · NISAR ${site.product}` : ""}
        </p>
        <h2>{finding.story.title}</h2>
        <p className="muted small">{finding.story.question}</p>
      </header>
      {finding.moments?.length > 1 && onChangeMoment && (
        <label className="finding-moment small">
          Moment{" "}
          <select value={finding.moment ?? ""} onChange={(e) => onChangeMoment(Number(e.target.value))}>
            {finding.moments.map((m) => (
              <option key={m.index} value={m.index}>{m.title} ({m.display})</option>
            ))}
          </select>
        </label>
      )}
    </>
  );
}

function ClaimSection({ finding }) {
  const { claim } = finding;
  const measured = claim.measured;
  const channels = !measured && finding.site.channels ? ` · ${finding.site.channels}` : "";
  return (
    <section className="finding-claim" aria-label="What NISAR measured">
      <p className="finding-badge small">{measured ? "Measured" : "Before & after, not measured"}</p>
      <p className={`finding-value${measured ? "" : " finding-value-text"}`}>{claim.display}</p>
      <p className="finding-caption">{claim.caption}</p>
      <p className="muted small">
        {measured ? `${claim.label} · ${claim.detail} · ` : ""}{period(claim)}{channels}
      </p>
    </section>
  );
}

function ConfidenceSection({ id, confidence, recordPasses }) {
  const gap = confidence.longest_gap_days ? `, at most ${confidence.longest_gap_days} days apart` : "";
  return (
    <section className="finding-section" aria-labelledby={id}>
      <h3 id={id}>What this rests on</h3>
      <p className="small">
        {plural(confidence.passes, "pass", "passes")} in this period{gap}; the
        record holds {recordPasses} over {confidence.record_days} days.
      </p>
      {confidence.notes.length > 0 && (
        <ul className="finding-notes small">{confidence.notes.map((n) => <li key={n}>{n}</li>)}</ul>
      )}
    </section>
  );
}

const orDash = (v) => v ?? "–";

/** The passes behind the claim, one row each. */
function EvidenceTable({ claim, passes, footprint }) {
  const measured = claim.measured;
  const showVisible = passes.some((p) => p.visible_value != null && p.visible_value !== p.value);
  const showMode = new Set(passes.map((p) => p.mode).filter(Boolean)).size > 1;
  return (
    <div className="finding-table-wrap">
      <table className="finding-table small">
        <thead>
          <tr>
            <th scope="col">Pass</th>
            {measured && <th scope="col">{footprint ? `${claim.unit}, shared area` : claim.unit}</th>}
            {showVisible && <th scope="col">{claim.unit}, pixels it imaged</th>}
            {showMode && <th scope="col">Mode</th>}
            <th scope="col">Quality</th>
            <th scope="col">Box imaged</th>
          </tr>
        </thead>
        <tbody>
          {passes.map((p) => (
            <tr key={p.date}>
              <td>{fmt(p.date)}</td>
              {measured && <td className="num">{orDash(round(p.value))}</td>}
              {showVisible && <td className="num">{orDash(round(p.visible_value))}</td>}
              {showMode && <td><code>{orDash(p.mode)}</code></td>}
              <td>{orDash(p.quality)}</td>
              <td className="num">{p.valid_pct != null ? `${Math.round(p.valid_pct)}%` : "–"}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

/** How open water is compared when not every pass imaged the whole box. */
function FootprintNote({ footprint }) {
  if (!footprint || footprint.status !== "ok" || footprint.pct_of_box >= 99.95) return null;
  const estimated = footprint.method === "image" && footprint.estimated?.length
    ? ` Values for passes that imaged more are estimated from the scene images, to within about ±${footprint.uncertainty_pp} points.`
    : "";
  return (
    <p className="small muted">
      Open water is compared over the {footprint.pct_of_box}% of the box that all {footprint.passes} passes imaged.
      {estimated}
    </p>
  );
}

function EvidenceSection({ id, claim, evidence }) {
  const granules = evidence.passes.filter((p) => p.granule_id);
  return (
    <section className="finding-section" aria-labelledby={id}>
      <h3 id={id}>Evidence</h3>
      <EvidenceTable claim={claim} passes={evidence.passes} footprint={evidence.footprint} />
      <FootprintNote footprint={evidence.footprint} />
      {granules.length > 0 && (
        <details className="small finding-granules">
          <summary>Granule IDs</summary>
          <ul>{granules.map((p) => <li key={p.granule_id}><code>{p.granule_id}</code></li>)}</ul>
        </details>
      )}
      {evidence.sources?.length > 0 && (
        <p className="small">
          Reported by:{" "}
          {evidence.sources.map((s, i) => (
            <span key={s.url}>{i > 0 && " · "}<a href={s.url} target="_blank" rel="noreferrer">{s.label}</a></span>
          ))}
        </p>
      )}
    </section>
  );
}

function HypothesesSection({ id, finding }) {
  const { hypotheses } = finding;
  const compare = finding.compare_with ?? [];
  if (hypotheses.length === 0 && compare.length === 0) return null;
  return (
    <section className="finding-section" aria-labelledby={id}>
      <h3 id={id}>Possible explanations</h3>
      {hypotheses.length > 0 && (
        <>
          <p className="small muted">{finding.hypothesis_label}.</p>
          <ul className="finding-hyps">
            {hypotheses.map((h) => (
              <li key={h.id}>
                <strong>{h.driver}.</strong> {h.mechanism}
                <p className="small muted">{h.channel}</p>
                <p className="small"><strong>Fits:</strong> {h.consistent_with}</p>
                <p className="small"><strong>But:</strong> {h.alternative}</p>
                <p className="small"><strong>Test:</strong> {h.test}</p>
              </li>
            ))}
          </ul>
        </>
      )}
      {compare.length > 0 && (
        <p className="small muted">
          Compare with: {compare.map((d) => `${d.label} (${d.summary})`).join("; ")}.{" "}
          {finding.comparison_note}
        </p>
      )}
    </section>
  );
}

function LimitsSection({ id, finding }) {
  return (
    <section className="finding-section" aria-labelledby={id}>
      <h3 id={id}>What this can&apos;t show</h3>
      <ul className="small">{finding.cant_see.map((c) => <li key={c}>{c}</li>)}</ul>
      {finding.next && <p className="small"><strong>With a longer record:</strong> {finding.next.application}</p>}
    </section>
  );
}

function CiteSection({ id, finding }) {
  return (
    <section className="finding-section finding-cite" aria-labelledby={id}>
      <h3 id={id}>Cite</h3>
      <p className="small">{finding.citation}</p>
      <p className="small muted">{finding.caveat}</p>
    </section>
  );
}

/** A button that copies `text`, saying for a moment whether it worked. */
function CopyButton({ label, text }) {
  const [state, setState] = useState(null);
  const onClick = async () => {
    setState((await copy(text)) ? "copied" : "blocked");
    window.setTimeout(() => setState(null), 1800);
  };
  const shown = { copied: "Copied ✓", blocked: "Copy blocked" }[state] ?? label;
  return (
    <button type="button" className="btn btn-small btn-secondary" onClick={onClick}>
      {shown}
    </button>
  );
}

function SaveButton({ saved, onSave }) {
  if (saved) return <button type="button" className="btn btn-small btn-secondary" disabled>Saved in My findings</button>;
  if (!onSave) return null;
  return <button type="button" className="btn btn-small btn-secondary" onClick={onSave}>Save to My findings…</button>;
}

/** Show it on the map, save it, and every way to share or reproduce it. */
function FindingActions({ finding, saved, onSave, onShowOnMap }) {
  const { links } = finding;
  const briefHref = `/brief/${finding.story.slug}${finding.moment != null ? `?moment=${finding.moment}` : ""}`;
  const mcp = JSON.stringify({ tool: links.mcp.tool, arguments: links.mcp.arguments }, null, 2);
  return (
    <footer className="finding-actions" aria-label="Share and reproduce">
      <div className="finding-actions-row">
        {onShowOnMap && (
          <button type="button" className="btn btn-small btn-primary" onClick={() => onShowOnMap(finding)}>
            Show on map
          </button>
        )}
        <SaveButton saved={saved} onSave={onSave && (() => onSave(findingRef(finding), finding))} />
        <CopyButton label="Copy link" text={`${window.location.origin}${links.workspace}`} />
        <a className="btn btn-small btn-secondary" href={briefHref} target="_blank" rel="noreferrer">Printable brief</a>
        <CopyButton label="Copy citation" text={finding.citation} />
      </div>
      <details className="finding-more small">
        <summary>Data &amp; code</summary>
        <div className="finding-actions-row">
          {links.csv && (
            <a className="btn btn-small btn-secondary" href={absoluteApiUrl(links.csv)} download>Download CSV</a>
          )}
          {links.geojson && (
            <a className="btn btn-small btn-secondary" href={absoluteApiUrl(links.geojson)} download>Download GeoJSON</a>
          )}
          <CopyButton label="Copy API call" text={`curl "${absoluteApiUrl(links.api)}"`} />
          <CopyButton label="Copy MCP call" text={mcp} />
        </div>
      </details>
    </footer>
  );
}

/**
 * An evidence card: one moment of a curated story, as the app measured it,
 * to keep and share. The measured claim, the passes behind it, what the
 * record can and can't carry, labelled hypotheses, and every way to
 * reproduce it (link, CSV, REST, MCP, printable brief). Built by the API
 * (`/api/findings/<slug>`), so the card, the REST call and the MCP tool all
 * return the same thing. A story's "Save / share" opens it.
 */
export default function FindingCard({
  slug,
  moment = null,
  variant = "panel",
  saved = false,
  onSave,
  onShowOnMap,
  onChangeMoment,
}) {
  const { data: finding, error } = useQuery(findingQuery(slug, moment));
  if (error) return <p className="panel error" role="alert">{error.message || "Couldn't build this finding."}</p>;
  if (!finding) return <p className="panel muted" role="status">Building the finding…</p>;

  return (
    <article className={`finding-card finding-${variant}`} aria-label={`Finding: ${finding.story.title}`}>
      <FindingHead finding={finding} onChangeMoment={onChangeMoment} />
      <ClaimSection finding={finding} />
      <ConfidenceSection id={`fc-conf-${slug}`} confidence={finding.confidence} recordPasses={finding.evidence.record_passes} />
      <EvidenceSection id={`fc-ev-${slug}`} claim={finding.claim} evidence={finding.evidence} />
      <HypothesesSection id={`fc-hyp-${slug}`} finding={finding} />
      <LimitsSection id={`fc-cant-${slug}`} finding={finding} />
      <CiteSection id={`fc-cite-${slug}`} finding={finding} />
      {variant !== "brief" && (
        <FindingActions finding={finding} saved={saved} onSave={onSave} onShowOnMap={onShowOnMap} />
      )}
    </article>
  );
}
