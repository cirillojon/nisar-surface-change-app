import { useEffect, useRef, useState } from "react";

const NEW_STORY = "__new__";

/**
 * Save what is on the map, or a story's moment, to My findings. The viewer
 * writes the title and notes; the evidence below them is what the app
 * measured and is saved alongside, unchanged, so it can always be told
 * apart from the viewer's interpretation.
 */
export default function SaveFindingDialog({ draft, stories = [], onSave, onCancel }) {
  const [title, setTitle] = useState(draft.title ?? "");
  const [notes, setNotes] = useState(draft.notes ?? "");
  const [storyId, setStoryId] = useState("");
  const [newStory, setNewStory] = useState("");
  const dialogRef = useRef(null);
  const titleRef = useRef(null);

  useEffect(() => {
    titleRef.current?.focus();
    titleRef.current?.select();
  }, []);

  useEffect(() => {
    const onKey = (event) => {
      if (event.key === "Escape") {
        event.stopPropagation();
        onCancel();
      }
    };
    window.addEventListener("keydown", onKey, true);
    return () => window.removeEventListener("keydown", onKey, true);
  }, [onCancel]);

  const submit = (event) => {
    event.preventDefault();
    onSave(
      { ...draft, title: title.trim() || draft.title || "Untitled finding", notes: notes.trim() },
      { storyId: storyId === NEW_STORY ? null : storyId || null, newStory: storyId === NEW_STORY ? newStory.trim() || "Untitled story" : null },
    );
  };

  const e = draft.evidence ?? {};
  const v = draft.view ?? {};
  const facts = [
    ["Place", v.name],
    ["Measurement", e.label && e.display ? `${e.label}: ${e.display}` : e.display ?? e.label],
    ["What the app showed", e.caption],
    ["Dates", e.start && e.end && e.start !== e.end ? `${e.start} to ${e.end}` : e.date ?? e.start],
    ["Map layer", v.layerLabel],
    ["Acquisition mode", e.mode],
    ["Compared over", e.footprint],
    ["Source", e.source],
  ].filter(([, value]) => value);

  return (
    <div className="save-backdrop">
      <form
        className="save-dialog"
        role="dialog"
        aria-modal="true"
        aria-labelledby="save-dialog-title"
        ref={dialogRef}
        onSubmit={submit}
        data-tour="save-dialog"
      >
        <h2 id="save-dialog-title">Save to My findings</h2>
        <label className="save-field">
          <span>Title</span>
          <input ref={titleRef} value={title} onChange={(ev) => setTitle(ev.target.value)} maxLength={140} />
        </label>
        <label className="save-field">
          <span>
            Your notes <span className="muted">· your interpretation, kept apart from the app&apos;s analysis</span>
          </span>
          <textarea
            value={notes}
            onChange={(ev) => setNotes(ev.target.value)}
            rows={4}
            maxLength={4000}
            placeholder="What do you see, and what would you check next?"
          />
        </label>
        <section className="save-evidence" aria-label="From the data">
          <p className="save-evidence-head">From the data · generated by the app, saved as is</p>
          <dl>
            {facts.map(([term, value]) => (
              <div key={term}>
                <dt>{term}</dt>
                <dd>{value}</dd>
              </div>
            ))}
          </dl>
        </section>
        <label className="save-field">
          <span>Add to one of your stories <span className="muted">(optional)</span></span>
          <select value={storyId} onChange={(ev) => setStoryId(ev.target.value)}>
            <option value="">Don&apos;t add to a story</option>
            {stories.map((s) => (
              <option key={s.id} value={s.id}>{s.title}</option>
            ))}
            <option value={NEW_STORY}>New story…</option>
          </select>
        </label>
        {storyId === NEW_STORY && (
          <label className="save-field">
            <span>New story&apos;s title</span>
            <input value={newStory} onChange={(ev) => setNewStory(ev.target.value)} maxLength={140} placeholder="e.g. Monsoon water, observed" />
          </label>
        )}
        <p className="small muted">Saved in this browser only. Nothing is uploaded.</p>
        <div className="save-actions">
          <button type="button" className="btn btn-secondary" onClick={onCancel}>Cancel</button>
          <button type="submit" className="btn btn-primary" data-tour="save-submit">Save</button>
        </div>
      </form>
    </div>
  );
}
